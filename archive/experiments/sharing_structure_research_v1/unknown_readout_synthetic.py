def make_case(root, plan, case, number, old):
    rng = np.random.default_rng(plan["seed"] + 100003 * number)
    index, code = comparator_teacher(old, case)
    readout = rng.uniform(0.5, 1.5, (4, 16, 1)) * rng.choice((-1, 1), (4, 16, 1))
    offset = rng.normal(0, 0.3, (4, 1))
    np.savez_compressed(
        root / "private" / f"{case['name']}.npz",
        index=index,
        codes=code,
        readout=readout,
        offset=offset,
    )
    order = rng.permutation(16)
    positive = np.geomspace(plan["axis_min"], plan["axis_max"], plan["axis_points"])
    vpositive = np.sqrt(positive[:-1] * positive[1:])
    s, vs = np.r_[-positive[::-1], 0, positive], np.r_[-vpositive[::-1], 0, vpositive]
    panels = {}
    for name, grid in [("axis", s), ("axis_v", vs)]:
        x = np.zeros((16, len(grid), 16))
        for d in range(16):
            x[d, :, d] = grid
        panels[name] = x.reshape(-1, 16)
    for phase in range(2):
        panels[f"prefix_{phase}"] = prefix_inputs(
            rng, order, plan["slice_points"], {**plan, **case}
        )
        panels[f"prefix_v_{phase}"] = prefix_inputs(
            rng, order, plan["prefix_validation"], {**plan, **case}
        )
    for name, count in [
        ("fit", plan["fit_points"]),
        ("h0", plan["fit_validation"]),
        ("h1", plan["fit_validation"]),
        ("meta", plan["meta_points"]),
    ]:
        panels[name] = rng.normal(size=(count, 16))
    arrays = {"order": order, "axis_s": s, "axis_vs": vs}
    zero = teacher_output(np.zeros((1, 16)), index, code, readout, offset, 0.15)[:, 0]
    zero_noise = rng.normal(size=zero.shape)
    for condition, sigma in enumerate(plan["noise"]):
        arrays[f"zero_y_{condition}"] = zero + sigma * zero_noise / math.sqrt(
            32 * plan["axis_repeats"]
        )
    for name, x in panels.items():
        arrays[name + "_x"] = x
        y = teacher_output(x, index, code, readout, offset, 0.15)
        noise = rng.normal(size=y.shape)
        repeats = (
            plan["axis_repeats"]
            if name.startswith("axis")
            else plan["slice_repeats"]
            if name.startswith("prefix")
            else plan["fit_repeats"]
        )
        for condition, sigma in enumerate(plan["noise"]):
            arrays[f"{name}_y_{condition}"] = y + sigma * noise / math.sqrt(repeats)
    np.savez_compressed(root / "data" / f"{case['name']}.npz", **arrays)


def bootstrap(root, plan, case, condition):
    output = root / "source" / f"{case['name']}_{condition}"
    output.mkdir(exist_ok=False)
    data = observations(root, case, condition)
    axis, traces, indices = [], [], []
    for task in range(4):
        y = data["axis_y"][task].reshape(16, -1, 1).transpose(1, 0, 2)
        vy = data["axis_v_y"][task].reshape(16, -1, 1).transpose(1, 0, 2)
        code, axis_trace = wide_axis(
            data["axis_s"],
            y,
            data["axis_vs"],
            vy,
            {**plan, **case},
            plan["seed"] + task,
        )
        index, trace = extract(
            data, code, {**plan, **case}, task, 0, plan["noise"][condition]
        )
        axis.append(code)
        traces.append({"task": task, "axis": axis_trace, "search": trace})
        if trace["complete"]:
            indices.append(canonical_index(index, 4))
        print(
            json.dumps(
                {
                    "case": case["name"],
                    "condition": condition,
                    "task": task,
                    "phase": "bootstrap",
                    "complete": trace["complete"],
                    "code": code.tolist(),
                    "seconds": trace["seconds"],
                }
            ),
            flush=True,
        )
    unique = {index.tobytes(): index for index in indices}
    bank = (
        np.stack(list(unique.values()))
        if unique
        else np.empty((0, 16, 16), dtype=np.int16)
    )
    np.savez_compressed(
        output / "bootstrap_bank.npz", indices=bank, axis_codes=np.stack(axis)
    )
    save_json(
        output / "bootstrap_trace.json", {"tasks": traces, "frozen_utc": timestamp()}
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "action",
        choices=[
            "prepare",
            "bootstrap",
            "fit_bootstrap",
            "repeat",
            "fit_final",
            "select",
            "audit",
        ],
    )
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--case", type=int, default=0)
    parser.add_argument("--condition", type=int, default=0)
    parser.add_argument("--device", default="cpu")
    args = parser.parse_args()
    root = args.root.resolve()
    torch.set_num_threads(2)
    if args.action == "prepare":
        prepare(root)
        return
    plan = json.loads((root / "protocol.json").read_text())
    if args.action == "audit":
        audit(root, plan)
        return
    case = plan["cases"][args.case]
    if args.action == "bootstrap":
        bootstrap(root, plan, case, args.condition)
    elif args.action == "fit_bootstrap":
        fit_bank(root, plan, case, args.condition, 0, args.device)
    elif args.action == "repeat":
        repeat(root, plan, case, args.condition)
    elif args.action == "fit_final":
        fit_bank(root, plan, case, args.condition, 1, args.device)
    else:
        select(root, plan, case, args.condition, args.device)


if __name__ == "__main__":
    main()
