def wide_axis(s, values, vs, validation, spec, seed):
    count = spec["codes"]
    y, vy = values.reshape(len(s), -1), validation.reshape(len(vs), -1)
    positive = s > 0
    slopes = np.diff(y[positive], axis=0) / np.diff(s[positive])[:, None]
    energy = np.linalg.norm(np.diff(slopes, axis=0), axis=1)
    locations = s[positive][1:-1]
    peaks, _ = find_peaks(energy)
    peaks = peaks[np.argsort(energy[peaks])[::-1]]
    initial = []
    for peak in peaks:
        candidate = abs(spec["bias"]) / locations[peak]
        if 1e-4 < candidate < 16 and all(
            abs(math.log(candidate / old)) > 0.04 for old in initial
        ):
            initial.append(candidate)
        if len(initial) == count:
            break
    rng = np.random.default_rng(seed)
    starts = [np.geomspace(0.1, 2, count), np.geomspace(0.3, 1.5, count)]
    if len(initial) == count:
        starts.insert(0, np.sort(initial))
    while len(starts) < 7:
        starts.append(np.exp(rng.uniform(np.log(0.03), np.log(3), count)))

    def residual(logcode):
        matrix = axis_dictionary(s, np.sort(np.exp(logcode)), spec["bias"])
        coefficients = np.linalg.lstsq(matrix, y, rcond=1e-12)[0]
        return (matrix @ coefficients - y).ravel()

    records = []
    for start in starts:
        fitted = least_squares(
            residual,
            np.log(start),
            bounds=(np.log(1e-4), np.log(16)),
            max_nfev=160,
            ftol=1e-12,
            xtol=1e-12,
            gtol=1e-12,
        )
        code = np.sort(np.exp(fitted.x))
        matrix = axis_dictionary(s, code, spec["bias"])
        coefficients = np.linalg.lstsq(matrix, y, rcond=1e-12)[0]
        score = float(
            np.mean((axis_dictionary(vs, code, spec["bias"]) @ coefficients - vy) ** 2)
        )
        records.append(
            {
                "code": code.tolist(),
                "validation_mse": score,
                "training_mse": float(np.mean(fitted.fun**2)),
                "evaluations": fitted.nfev,
            }
        )
    best = min(records, key=lambda row: row["validation_mse"])
    return np.array(best["code"]), {"starts": records, "selected": best}


